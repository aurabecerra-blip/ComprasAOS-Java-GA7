package com.aos.compras;

import java.sql.*;
import java.util.ArrayList;
import java.util.List;

/** Persistencia JDBC. Cada operación libera sus recursos con try-with-resources. */
public final class ProveedorRepository {
    private final String url;
    public ProveedorRepository(String url) throws SQLException {
        this.url = url;
        try (Connection conexion = conectar(); Statement sentencia = conexion.createStatement()) {
            sentencia.executeUpdate("CREATE TABLE IF NOT EXISTS proveedores ("
                + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                + "nombre VARCHAR(160) NOT NULL, nit VARCHAR(30) NOT NULL UNIQUE,"
                + "servicio VARCHAR(200) NOT NULL, contacto VARCHAR(120) NOT NULL,"
                + "correo VARCHAR(160) NOT NULL, telefono VARCHAR(30) NOT NULL)");
        }
    }
    private Connection conectar() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }
    public long insertar(Proveedor proveedor) throws SQLException {
        String sql = "INSERT INTO proveedores(nombre,nit,servicio,contacto,correo,telefono) VALUES(?,?,?,?,?,?)";
        try (Connection conexion = conectar();
             PreparedStatement sentencia = conexion.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            asignar(sentencia, proveedor);
            sentencia.executeUpdate();
            try (ResultSet claves = sentencia.getGeneratedKeys()) {
                if (!claves.next()) throw new SQLException("No se obtuvo el identificador.");
                return claves.getLong(1);
            }
        }
    }
    public List<Proveedor> consultar() throws SQLException {
        List<Proveedor> proveedores = new ArrayList<>();
        try (Connection conexion = conectar();
             PreparedStatement sentencia = conexion.prepareStatement("SELECT * FROM proveedores ORDER BY id");
             ResultSet filas = sentencia.executeQuery()) {
            while (filas.next()) proveedores.add(new Proveedor(filas.getLong("id"),
                filas.getString("nombre"), filas.getString("nit"), filas.getString("servicio"),
                filas.getString("contacto"), filas.getString("correo"), filas.getString("telefono")));
        }
        return proveedores;
    }
    public boolean actualizar(Proveedor proveedor) throws SQLException {
        String sql = "UPDATE proveedores SET nombre=?,nit=?,servicio=?,contacto=?,correo=?,telefono=? WHERE id=?";
        try (Connection conexion = conectar(); PreparedStatement sentencia = conexion.prepareStatement(sql)) {
            asignar(sentencia, proveedor);
            sentencia.setLong(7, proveedor.id());
            return sentencia.executeUpdate() == 1;
        }
    }
    public boolean eliminar(long id) throws SQLException {
        try (Connection conexion = conectar();
             PreparedStatement sentencia = conexion.prepareStatement("DELETE FROM proveedores WHERE id=?")) {
            sentencia.setLong(1, id);
            return sentencia.executeUpdate() == 1;
        }
    }
    private void asignar(PreparedStatement sentencia, Proveedor proveedor) throws SQLException {
        sentencia.setString(1, proveedor.nombre()); sentencia.setString(2, proveedor.nit());
        sentencia.setString(3, proveedor.servicio()); sentencia.setString(4, proveedor.contacto());
        sentencia.setString(5, proveedor.correo()); sentencia.setString(6, proveedor.telefono());
    }
}
